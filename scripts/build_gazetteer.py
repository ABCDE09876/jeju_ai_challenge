def read_example_codes() -> dict[str, str]:
    """공식 예시데이터(유동인구 시트)에 실린 행정동 코드를 읽어 우선 적용한다."""
    found: dict[str, str] = {}
    if not CATALOG_SCHEMA_PATH.exists():
        return found
    schema = json.loads(CATALOG_SCHEMA_PATH.read_text(encoding="utf-8"))
    for sheet in schema.get("center_examples", []):
        for row in sheet.get("example_rows", []):
            name = row.get("emd_nm", "")
            code = row.get("emd_cd", "")
            if name and code:
                found[name.split()[-1]] = code
    return found


def build_gazetteer() -> dict:
    example_codes = read_example_codes()
    regions = []
    for name, city, kind, code, district, lat, lon, legal, confidence, partner in REGION_ROWS:
        verified = example_codes.get(name)
        regions.append({
            "emd_nm": name,
            "full_nm": f"{city} {name}",
            "city": city,
            "kind": kind,
            "emd_cd": verified or code,
            "code_status": "official_example" if verified else "standard_pattern",
            "dstrct_se": district,
            "lat": lat,
            "lon": lon,
            "coord_status": "approximate",
            "legal_dongs": legal,
            "mapping_confidence": confidence,
            "partner_hint": partner,
        })
    aliases = [
        {"alias": alias, "targets": targets, "kind": kind, "partner_hint": partner, "note": note}
        for alias, targets, kind, partner, note in ALIAS_ROWS
    ]
    landmarks = [
        {"name": name, "emd_nm": emd, "lat": lat, "lon": lon, "kind": kind, "schedule": rule, "coord_status": "approximate"}
        for name, emd, lat, lon, kind, rule in LANDMARK_ROWS
    ]
    stations = [
        {
            "bus_station_id": sid, "bus_station_name": label, "emd_nm": emd, "lat": lat, "lon": lon,
            "bus_city_type": city_type, "id_status": status,
            "coord_status": "official_example" if sid == "1" else "approximate",
        }
        for sid, label, emd, lat, lon, city_type, status in STATION_ROWS
    ]
    observatories = [
        {"observatory_code": code, "observatory_name": label, "lat": lat, "lon": lon, "coord_status": status}
        for code, label, lat, lon, status in WEATHER_ROWS
    ]
    names = {row["emd_nm"] for row in regions}
    problems = [a["alias"] for a in aliases if not set(a["targets"]) <= names]
    problems += [s["bus_station_name"] for s in stations if s["emd_nm"] not in names]
    problems += [m["name"] for m in landmarks if m["emd_nm"] not in names]
    if len(regions) != 43 or problems:
        raise ValueError(f"사전 정합성 오류: regions={len(regions)}, 미정의 대상={problems}")
    return {
        "version": "2026-11-16",
        "region_count": len(regions),
        "notes": [
            "행정기관코드 8자리: 공식 예시데이터에 실린 코드는 official_example, 나머지는 행정표준코드 체계에 맞춘 standard_pattern(원자료 적재 시 재확인).",
            "좌표는 반경 계산·시각화를 위한 근사값(approximate). 국제여객선터미널 정류소와 중문 관측소만 공식 예시값.",
            "법정동-행정동 관할 중 mapping_confidence=review 항목은 행정안전부 관할구역 자료로 재확인 필요.",
            "정류소 ID 1(국제여객선터미널)·96(제주민속오일장)은 공식 예시데이터 값, 9000번대는 합성 식별자.",
        ],
        "regions": regions,
        "aliases": aliases,
        "landmarks": landmarks,
        "bus_stations": stations,
        "weather_stations": observatories,
    }


def main() -> int:
    gazetteer = build_gazetteer()
    GAZETTEER_PATH.parent.mkdir(parents=True, exist_ok=True)
    GAZETTEER_PATH.write_text(json.dumps(gazetteer, ensure_ascii=False, indent=1), encoding="utf-8")
    official = sum(1 for r in gazetteer["regions"] if r["code_status"] == "official_example")
    print(f"읍면동 {gazetteer['region_count']}개(공식 예시 코드 확인 {official}개), 별칭 {len(gazetteer['aliases'])}개, "
          f"정류소 {len(gazetteer['bus_stations'])}개, 관측소 {len(gazetteer['weather_stations'])}개")
    print(f"저장 완료: {GAZETTEER_PATH.relative_to(GAZETTEER_PATH.parents[2])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
