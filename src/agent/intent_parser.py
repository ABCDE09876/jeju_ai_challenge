def detect_own_topic(text: str, topic: str) -> str:
    """후속 질문 자체의 주제. '장날 당일은요?'의 장날, '그럼 새벽 6시에는?'의 새벽처럼 조건으로 쓰인 낱말은 주제가 아니다."""
    if topic == "general":
        return topic
    return detect_topic(CONDITION_TIME.sub(" ", MARKET_DAY.sub(" ", MARKET_OPEN.sub(" ", text)))
                        .replace("장날", " ").replace("오일장", " "))


def is_followup(text: str, plan: QueryPlan, previous: QueryPlan | None = None) -> bool:
    """후속 질문 판정. 주제어·주장이 담긴 새 질문은 짧아도 독립 질문으로 본다(앞 질문과 같은 주제만 있으면 후속 질문)."""
    stripped = text.strip()
    if has_cue(stripped, FOLLOWUP_CUES):
        return True
    if len(stripped) <= 20 and re.search(r"(은|는|요|면|엔|땐)\s*\?*$", stripped):
        return True
    areas = plan.areas
    if areas and set(plan.area_labels) <= set(MARKET_ALIASES) and extract_day(stripped) == "market" \
            and not any(alias in MARKET_DAY.sub(" ", stripped).replace("장날", " ") for alias in MARKET_ALIASES):
        areas = []  # '오일장 열리는 날은 어떤지 알려주세요'의 오일장은 날짜 조건이지 지역이 아니다
    if len(stripped) <= 30 and len(areas) == 1 and any(c in stripped for c in PARTNER_CUES):
        return True  # '예래동 비교', '추자면보다는?'처럼 비교 상대만 짧게 바꾸는 후속 질문
    if len(areas) == 1 and re.search(r"비교|견주|대보(?!름)", stripped):
        return True  # '삼양이랑 비교해 주시면 안 될까요? 블로그에 올리려고요'처럼 길게 부탁하는 비교 상대 지정(다양성 시험에서 보강)
    own_topic = detect_own_topic(stripped, plan.topic)
    standalone = own_topic != "general" or plan.intent == "fact_check"
    place_ask = bool(PLACE_QUESTION.search(stripped)) and not re.search(
        r"둘|두\s*(?:곳|동네|지역|군데)|그\s*중|이\s*중|그중|이중|(?<![가-힣])(?:더|덜)(?![가-힣])", stripped)
    if not areas and previous is not None and own_topic == previous.topic and plan.intent != "fact_check" \
            and len(stripped) <= 100 and not place_ask:
        return True  # '출근 시간에는 어떻게 운영되는지 알려 주세요'처럼 앞 질문과 같은 주제로 조건만 바꾸는 질문
    if len(areas) == 1 and not standalone and len(stripped) <= 100 and plan.hour_from is None \
            and plan.weather == "any" and plan.day_type == "any" and plan.user_group is None \
            and not NEW_SUBJECT.search(stripped):
        return True  # '남원읍 쪽은 어때.'처럼 지역만 바꿔 같은 것을 묻는 짧은 후속 질문(다양성 시험에서 보강)
    return len(stripped) <= 80 and not areas and not standalone and not place_ask  # 공손한 긴 후속 질문도 포함


def merge_dialogue_context(plan: QueryPlan, previous: QueryPlan | None) -> QueryPlan:
    """이전 질문의 지역·주제·조건을 이어받아 생략된 슬롯을 채운다."""
    if previous is None or plan.intent in ("help", "catalog"):
        return plan
    text = plan.question
    if not is_followup(text, plan, previous):
        return plan
    followup = True
    inherited = []
    if plan.areas and any(cue in DAY_NEGATED.sub(" ", text) for cue in REPLACE_CUES):  # '평일 말고 주말은요?'의 '말고'는 지역을 바꾸지 않는다
        # '거기 말고 X랑 비교해 줘'는 앞 지역과 비교, '노형 말고 연동은?'은 지역만 바꾼다(다양성 시험에서 구별)
        if plan.areas and previous.areas and len(plan.areas) == 1 and REPLACE_PARTNER.search(text):
            anchor = previous.areas[0] if previous.areas[0] not in plan.areas else (previous.areas[1:2] or [""])[0]
            plan.areas = [a for a in [anchor] + plan.areas if a][:2]
            inherited.append("기준 지역")
    elif plan.areas and previous.areas and set(plan.area_labels) <= set(MARKET_ALIASES) and extract_day(text) == "market" \
            and not any(alias in MARKET_DAY.sub(" ", text).replace("장날", " ") for alias in MARKET_ALIASES):
        plan.areas, plan.area_labels = list(previous.areas), list(previous.area_labels)  # '오일장 열리는 날은요?'는 날짜만 바꾼다
        inherited.append("지역")
    elif not plan.areas and previous.areas:
        plan.areas = list(previous.areas)
        plan.area_labels = list(previous.area_labels)
        inherited.append("지역")
    elif plan.areas and len(plan.areas) == 1 and previous.areas and any(c in text for c in PARTNER_CUES):
        plan.areas = [previous.areas[0], plan.areas[0]] if previous.areas[0] != plan.areas[0] else plan.areas
        inherited.append("기준 지역")
    # '장날 당일은요?'의 장날은 날짜 조건이지 혼잡 주제가 아니므로 앞 질문의 주제를 이어받는다(다양성 시험 개발용에서 보강)
    # '그럼 새벽 6시에는?'의 새벽·밤도 시간 조건이지 야간 주제가 아니다
    own_topic = detect_own_topic(text, plan.topic)
    if own_topic == "general" and previous.topic != "general" and plan.topic != previous.topic:
        plan.topic = previous.topic
        inherited.append("주제")
        if plan.hour_from is not None:
            # '그럼 8시 이후는?' 처럼 오전·오후 표시가 없는 시각은 이어받은 주제(퇴근·야간 등) 기준으로 다시 해석한다.
            plan.hour_from, plan.hour_to = extract_hours(text, plan.topic)
    if plan.hour_from is None and plan.hour_to is None and previous.hour_from is not None:
        plan.hour_from, plan.hour_to = previous.hour_from, previous.hour_to
        inherited.append("시간대")
    if plan.weather == "any" and previous.weather != "any" and extract_weather(text) is None:
        plan.weather = previous.weather
        inherited.append("날씨")
    if plan.day_type == "any" and previous.day_type != "any" and not DAY_NEGATED.search(text):
        plan.day_type = previous.day_type
        inherited.append("요일")
    if plan.user_group is None and previous.user_group and not ADULT_GROUP.search(text):
        plan.user_group = previous.user_group
        inherited.append("이용자")
    # 후속 질문 자체가 방문 시각 질문('그럼 한산한 때는?')이면 앞 질문의 숨은 혼잡 의도로 덮지 않는다(6천만 시험 독립 검토에서 확인)
    strong_intent = plan.intent in ("fact_check", "hidden_slice") or (plan.intent == "boundary" and plan.variable == "visit_hour")
    if not strong_intent and previous.intent in ("compare", "profile", "boundary", "hidden_slice"):
        if plan.intent in ("profile", "compare") or followup:
            scan = SINCE_ADVERB.sub(" ", DAY_RANGE.sub(" ", text))
            if previous.intent == "boundary" or has_cue(scan, BOUNDARY_CUES) or AFTER_CLOCK.search(normalize_clock(scan)):
                plan.intent = "boundary"
                plan.variable = plan.variable or previous.variable or "return_hour"
                if plan.wait_minutes:
                    plan.variable = "wait_minutes"
            elif previous.intent == "hidden_slice":
                plan.intent = "hidden_slice"
            elif len(plan.areas) >= 2:
                plan.intent = "compare"
            inherited.append("의도")
    if plan.intent == "fact_check" and not plan.claim:
        plan.claim = text
    if plan.needs_abstain is None:
        reason, question = detect_abstention(text, plan.topic)
        plan.needs_abstain, plan.abstain_question = reason, question
    if plan.needs_abstain is None and own_topic == "general" and previous.needs_abstain \
            and previous.needs_abstain.startswith("'"):
        residue = normalize_clock(text)
        for match in load_place_index().find_places(text):
            residue = residue.replace(match.query, " ")
        if not re.search(r"[가-힣A-Za-z]{2,}", BARE_FOLLOWUP.sub(" ", residue)):
            plan.needs_abstain, plan.abstain_question = previous.needs_abstain, previous.abstain_question
            inherited.append("판정 보류")
    plan.inherited = inherited
    return plan
