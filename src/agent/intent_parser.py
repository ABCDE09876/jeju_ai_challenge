def find_cue(text: str, cue: str) -> int:
    """단서어 위치(-1 = 없음). 가운데 띄어쓰기가 든 단서어('몇 시에 가')는 붙여 쓰거나 더 띄어 써도 찾는다."""
    pattern = CUE_PATTERNS.get(cue)
    if pattern is None:
        if " " not in cue.strip() or cue != cue.strip() or cue in LITERAL_CUES:
            return text.find(cue)
        pattern = CUE_PATTERNS[cue] = re.compile(r"\s*".join(re.escape(part) for part in cue.split()))
    found = pattern.search(text)
    return found.start() if found else -1


def has_cue(text: str, cues) -> bool:
    return any(find_cue(text, cue) >= 0 for cue in cues)


