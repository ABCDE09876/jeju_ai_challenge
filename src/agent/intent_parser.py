def locate_topic(text: str, topic: str, words) -> int:
    """주제어(단어 목록 또는 보강 패턴)가 처음 나온 위치. 없으면 -1."""
    positions = [p for p in (find_cue(text, word) for word in words) if p >= 0]
    pattern = TOPIC_PATTERNS.get(topic)
    found = pattern.search(text) if pattern else None
    if found:
        positions.append(found.start())
    return min(positions) if positions else -1


def find_first_topic(text: str) -> str:
    best, best_position = "general", len(text) + 1
    for topic, words in TOPIC_RULES:
        position = locate_topic(text, topic, words)
        if 0 <= position < best_position:
            best, best_position = topic, position
    return best


