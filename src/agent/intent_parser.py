def list_vowel_slips(word: str) -> list[str]:
    """낱말에서 음절 하나의 모음만 헷갈려 쓴 꼴들."""
    slips = []
    for offset, char in enumerate(word):
        code = ord(char) - 0xAC00
        vowel = (code % 588) // 28 if 0 <= code < 11172 else -1
        for group in VOWEL_SETS:
            if vowel in group:
                slips += [word[:offset] + chr(ord(char) + (other - vowel) * 28) + word[offset + 1:]
                          for other in group if other != vowel]
    return slips


